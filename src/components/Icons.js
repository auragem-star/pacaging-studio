/**
 * Create an icon element from the Icons map.
 * @param {string} name - key in Icons object
 * @param {string} size - CSS size string e.g. '18px'
 * @returns {HTMLElement}
 */
export function icon(name, size = '18px') {
  const wrapper = document.createElement('span');
  wrapper.className = 'icon';
  wrapper.style.display = 'inline-flex';
  wrapper.style.alignItems = 'center';
  wrapper.style.width = size;
  wrapper.style.height = size;
  wrapper.innerHTML = Icons[name] || Icons.info;
  const svg = wrapper.querySelector('svg');
  if (svg) {
    svg.style.width = '100%';
    svg.style.height = '100%';
  }
  return wrapper;
}
